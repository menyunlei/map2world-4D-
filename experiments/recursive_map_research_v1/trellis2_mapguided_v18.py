"""One fixed native-prior/map-guided inference test. No learned-weight updates."""
from paths import JOB,read,save,sha
from trellis2_prepare_v1 import DEST,REPO
from pathlib import Path
import argparse,numpy as np,sys
sys.path.insert(0,str(REPO))

OUT=JOB/'map_object_world_v1/trellis2_mapguided_v18'
V17=JOB/'map_object_world_v1/trellis2_native_street_v17'
V11=JOB/'map_object_world_v1/trellis2_map10_block_v11'
SEED=942217

def prepare():
    assert not OUT.exists()
    p=read(V17/'PLAN.json');m=read(V11/'PLAN.json');asset=read(V17/'ASSET.json')
    assert sha(p['input'])==p['input_sha256']
    maps={}
    for mode in ['correct','edit']:
        path=m['global_maps'][mode]
        with np.load(path) as z:fps=z['footprints'].copy()>.5
        assert fps.shape==(4,64,64) and fps.reshape(4,-1).any(1).all()
        maps[mode]={'path':path,'sha256':sha(path),'footprint_pixels':fps.sum((1,2)).tolist()}
        save(OUT/mode/'PLAN.json',{**p,'one_complete_scene_sample':True,
            'map_control_claim':'Untrained inference-time guidance under test, not learned map-module success'})
    g=asset['native_bounds'][0][2]
    plan={'scope':'Single zero-training map-guided native-prior attempt, original versus one footprint edit',
        'seed':SEED,'maps':maps,'edited_object_index':m['edited_object_index'],'input':p['input'],
        'input_sha256':p['input_sha256'],'runtime':p['runtime'],'reference_style':'same official classical urban block as v17',
        'reference_is_not_appearance_only':'Native image features retain geometry biases; map guidance effectiveness must be measured',
        'guidance':{'inner_steps':6,'lr':.05,'trust_RMS':.35,'prior_weight':.05,'active_t_max':.9,
            'positive':'Equal per-object softplus of negative projected decoder logits',
            'negative':'Softplus projected logits outside the four requested footprints',
            'projection':'Maximum native SS decoder logit above reference floor+4/64',
            'floor_native_reference':g,'building_z_start':int(np.ceil((g+.5)*64+4))},
        'sampler':'Original SS Euler schedule/CFG; only predicted-clean latent corrected using map energy during sampling',
        'native_Shape_and_texture_conditions':'Unchanged native image features, not failed map-only tokens',
        'no_native_support_masking_or_mesh_cutting':True,'model_training_updates':0,'no_adapter_or_LoRA':True,
        'layout':'Global native XY directly shares the normalized map cube; no per-building placement',
        'outside_scope':'Unannotated east-side buildings; four roof-proxy annotations are approximate, not surveyed footprints',
        'unknown_heights':'Not target-matched; generated by native prior',
        'world_from_native_z_translation':m['reference_ground']-g,'same_global_transform_for_both':True,
        'noise':'Same SS noise; sparse Shape/texture noise indexed by canonical coordinates and fixed stage seed',
        'pipeline':'native 1024_cascade, max49152, no optional hole filling; no geometry repair',
        'GPU_cap_seconds':7200,'single_attempt_no_tuning_or_training_extension':True}
    save(OUT/'PLAN.json',plan)
    frozen={str(JOB/n):sha(JOB/n) for n in ['trellis2_mapguided_v18.py','trellis2_mapguided_v18_guidance.py',
        'trellis2_mapguided_v18_generate.py','trellis2_mapguided_v18_views.py','trellis2_mapguided_v18_owner.py']}
    frozen.update({v['path']:v['sha256'] for v in maps.values()});frozen[p['input']]=p['input_sha256']
    frozen[str(OUT/'PLAN.json')]=sha(OUT/'PLAN.json');save(OUT/'SOURCE_FREEZE.json',frozen)
    print('NATIVE_MAP_GUIDANCE_REGISTERED',maps,flush=True)

def coarse(mode):
    from trellis2 import models
    from trellis2.modules import image_feature_extractor
    from trellis2.pipelines import Trellis2ImageTo3DPipeline
    from trellis2.pipelines.samplers import FlowEulerGuidanceIntervalSampler
    from trellis2_mapguided_v18_guidance import MapGuidedSampler
    import torch,hashlib
    from PIL import Image,ImageDraw
    torch.set_num_threads(4);p=read(OUT/'PLAN.json');cfg=read(Path(p['runtime'])/'pipeline.json')['args']
    mods={k:models.from_pretrained(cfg['models'][k]).eval().requires_grad_(False).cuda()
          for k in ['sparse_structure_flow_model','sparse_structure_decoder']}
    enc=getattr(image_feature_extractor,cfg['image_cond_model']['name'])(**cfg['image_cond_model']['args'])
    pipe=Trellis2ImageTo3DPipeline(models=mods,image_cond_model=enc,low_vram=True);pipe.cuda()
    with torch.no_grad():cond=pipe.get_cond([Image.open(p['input']).convert('RGB')],512)
    torch.manual_seed(SEED);noise=torch.randn((1,8,16,16,16)).cuda()
    target='correct' if mode=='baseline' else mode
    with np.load(p['maps'][target]['path']) as z:fps=z['footprints'].copy()>.5
    sampler=MapGuidedSampler(mods['sparse_structure_decoder'],fps,p['guidance'],enabled=mode!='baseline',**cfg['sparse_structure_sampler']['args'])
    with torch.no_grad():
        latent=sampler.sample(mods['sparse_structure_flow_model'],noise,**cond,**cfg['sparse_structure_sampler']['params'],verbose=False).samples
        logits=mods['sparse_structure_decoder'](latent).float();support=(logits>0)[0,0].cpu().numpy()
        support32=torch.nn.functional.max_pool3d((logits>0).float(),2,2)>.5
        coords=torch.argwhere(support32)[:,[0,2,3,4]].int().cpu().numpy()
    folder=OUT/mode;folder.mkdir(parents=True,exist_ok=True)
    with (folder/'SS.npz').open('xb') as f:np.savez_compressed(f,latent=latent.cpu().numpy(),support64=support,coords32=coords)
    proj=support[:,:,p['guidance']['building_z_start']:].any(-1).T;union=fps.any(0)
    per=[float((proj&fp).sum()/max(1,fp.sum())) for fp in fps]
    xy=np.argwhere(support)
    meta={'mode':mode,'support_cells':int(support.sum()),'coords32':len(coords),
        'above_ground_map_IoU':float((proj&union).sum()/max(1,(proj|union).sum())),
        'per_footprint_coverage':per,'outside_fraction':float((proj&~union).sum()/max(1,proj.sum())),
        'native_extent_cells':(np.ptp(xy,axis=0)+1).tolist() if len(xy) else [0,0,0],
        'SS_noise_sha256':hashlib.sha256(noise.cpu().numpy().tobytes()).hexdigest(),
        'model_training_updates':0,'latent_guidance_trace':sampler.trace,'no_GT_or_output_repair':True}
    assert all(q.grad is None for model in mods.values() for q in model.parameters())
    save(folder/'SS_METRICS.json',meta)
    image=Image.new('RGB',(768,282),'#121922');draw=ImageDraw.Draw(image)
    overlay=np.zeros((64,64,3),np.uint8)+20;overlay[proj]=[60,155,220];overlay[union]=[220,65,55];overlay[proj&union]=[230,210,95]
    panels=[overlay,np.repeat((support.any(1).T*180)[...,None],3,-1),np.repeat((support.any(0).T*180)[...,None],3,-1)]
    for j,rgb in enumerate(panels):image.paste(Image.fromarray(rgb[::-1].astype(np.uint8)).resize((256,256),Image.Resampling.NEAREST),(j*256,26))
    draw.text((4,4),f'{mode} native SS XY/map / XZ / YZ, IoU {meta["above_ground_map_IoU"]:.3f}',fill='white')
    image.save(folder/'SS.png');print('COARSE_MAP_GUIDANCE',meta,flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--prepare',action='store_true');p.add_argument('--mode',choices=['baseline','correct','edit']);a=p.parse_args()
    prepare() if a.prepare else coarse(a.mode)
